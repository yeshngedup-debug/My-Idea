<#
  Local development: full Supabase stack in Docker + this Next.js app.

  Run from anywhere:  powershell -ExecutionPolicy Bypass -File scripts/local-up.ps1

  What it does:
    1. supabase start       -> Postgres, Auth, REST, Storage, Studio in Docker
    2. supabase db reset    -> applies every migration + supabase/seeds/local-dev.sql
    3. reads the generated local keys and writes .env.local (backing up the old one)
    4. starts `npm run dev` on http://127.0.0.1:3000

  The seeded accounts and their fixed local-only password are written to
  .env.local so the Playwright flows can run immediately:
    admin@btc-e2e.test / student.tashi@btc-e2e.test /
    founder.dorji@btc-e2e.test   password: LocalTest123!
#>
$ErrorActionPreference = 'Stop'
Set-Location (Split-Path -Parent $PSScriptRoot)

Write-Host '==> Starting Supabase services in Docker...'
supabase start
if ($LASTEXITCODE -ne 0) { throw 'supabase start failed. Is Docker Desktop running?' }

Write-Host '==> Applying migrations and local seed...'
supabase db reset
if ($LASTEXITCODE -ne 0) { throw 'supabase db reset failed.' }

Write-Host '==> Reading local API credentials...'
$envLines = @(supabase status -o env)
$values = @{}
foreach ($line in $envLines) {
  if ($line -match '^([A-Za-z0-9_.]+)=(.*)$') {
    $value = $Matches[2].Trim()
    if ($value.StartsWith('"') -and $value.EndsWith('"')) {
      $value = $value.Substring(1, $value.Length - 2)
    }
    $values[$Matches[1].ToUpperInvariant()] = $value
  }
}

function Get-Value([string[]]$names) {
  foreach ($name in $names) {
    $key = $name.ToUpperInvariant()
    if ($values.ContainsKey($key) -and $values[$key]) { return $values[$key] }
  }
  throw "Could not read any of: $($names -join ', '). Check `supabase status -o env`."
}

$apiUrl = Get-Value @('API_URL', 'SUPABASE_URL', 'API.URL', 'SUPABASE_API_URL')
$anonKey = Get-Value @('ANON_KEY', 'SUPABASE_ANON_KEY', 'AUTH.ANON_KEY', 'SUPABASE_PUBLISHABLE_KEY')

if (Test-Path .env.local) {
  Copy-Item .env.local '.env.local.backup' -Force
  Write-Host '    Existing .env.local backed up to .env.local.backup'
}

$envFileContent = @"
# Generated by scripts/local-up.ps1 - points at the local Supabase Docker stack.
NEXT_PUBLIC_SUPABASE_URL=$apiUrl
NEXT_PUBLIC_SUPABASE_ANON_KEY=$anonKey
NEXT_PUBLIC_APP_URL=http://127.0.0.1:3000
CONTACT_EMAIL=hello@bhutantech.bt
# Local-only dummy values so the payment journey can be tested.
NEXT_PUBLIC_PAYMENT_ACCOUNT_NUMBER=LOCAL-TEST-000000
NEXT_PUBLIC_PAYMENT_MBOB_NUMBER=LOCAL-TEST-0000000

# Local-only seeded E2E accounts (password is in supabase/seeds/local-dev.sql)
E2E_STUDENT_EMAIL=student.tashi@btc-e2e.test
E2E_STUDENT_PASSWORD=LocalTest123!
E2E_FOUNDER_EMAIL=founder.dorji@btc-e2e.test
E2E_FOUNDER_PASSWORD=LocalTest123!
E2E_PAYMENT_FOUNDER_EMAIL=founder.pema@btc-e2e.test
E2E_PAYMENT_FOUNDER_PASSWORD=LocalTest123!
E2E_ADMIN_EMAIL=admin@btc-e2e.test
E2E_ADMIN_PASSWORD=LocalTest123!
"@

$envFileContent | Set-Content .env.local -Encoding utf8
# docker compose reads .env for variable substitution
$envFileContent | Set-Content .env -Encoding utf8

Write-Host '==> Local Supabase is ready. Starting Next.js...'
npm run dev
